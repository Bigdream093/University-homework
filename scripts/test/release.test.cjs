const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { buildInfo } = require('../build-info.cjs')
const { createManifest, verifyManifest } = require('../release-manifest.cjs')

test('构建指纹稳定，源码变动可追溯，服务端和桌面版本独立记录', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mohen-build-info-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  fs.mkdirSync(path.join(root, 'web/src'), { recursive: true })
  fs.mkdirSync(path.join(root, 'desktop/src'), { recursive: true })
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ version: '2.0.0' }))
  fs.writeFileSync(path.join(root, 'desktop/package.json'), JSON.stringify({ version: '1.9.0' }))
  const first = buildInfo(root)
  assert.equal(buildInfo(root).source_sha256, first.source_sha256)
  fs.writeFileSync(path.join(root, 'web/src/main.js'), 'changed')
  assert.notEqual(buildInfo(root).source_sha256, first.source_sha256)
  const release = path.join(root, 'delivery')
  fs.mkdirSync(release)
  fs.writeFileSync(path.join(release, 'university-homework-2.0.0-linux-amd64.tar'), 'fixture only')
  const manifest = createManifest(release, ['server'], root)
  assert.equal(manifest.delivery, 'server-only')
  assert.equal(manifest.desktop.version, '1.9.0')
  assert.equal(manifest.components['teacher-win'].status, 'not-built')
  assert.equal(manifest.compatibility.status, 'not-verified')
  assert.equal(verifyManifest(release).source.version, '2.0.0')
  assert.throws(() => createManifest(release, ['server', 'teacher-win'], root), /缺少发布目标/)
  fs.appendFileSync(path.join(release, 'university-homework-2.0.0-linux-amd64.tar'), 'tampered')
  assert.throws(() => verifyManifest(release), /被修改/)
})

test('发布校验拒绝私有配置、空产物、额外文件和被改动的校验清单', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mohen-release-check-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  fs.mkdirSync(path.join(root, 'desktop'))
  fs.writeFileSync(path.join(root, 'package.json'), '{"version":"1.0.0"}')
  fs.writeFileSync(path.join(root, 'desktop/package.json'), '{"version":"1.0.0"}')
  const release = path.join(root, 'delivery')
  fs.mkdirSync(release)
  const artifact = path.join(release, 'university-homework-1.0.0-linux-amd64.tar')
  fs.writeFileSync(artifact, '')
  assert.throws(() => createManifest(release, ['server'], root), /缺少发布目标/)
  fs.writeFileSync(artifact, 'fixture only')
  fs.writeFileSync(path.join(release, '.env'), 'test-only')
  assert.throws(() => createManifest(release, ['server'], root), /私有数据/)
  fs.unlinkSync(path.join(release, '.env'))
  createManifest(release, ['server'], root)
  fs.appendFileSync(path.join(release, 'SHA256SUMS.txt'), 'tampered')
  assert.throws(() => verifyManifest(release), /SHA256SUMS/)
  createManifest(release, ['server'], root)
  fs.writeFileSync(path.join(release, 'unrecorded.txt'), 'extra')
  assert.throws(() => verifyManifest(release), /未记录文件/)
})
